import io
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def _num(v) -> str:
    return f"{v:,.2f}"


def generate_invoice_pdf(data: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("InvTitle", parent=styles["Heading1"], fontSize=16, textColor=colors.HexColor("#2563eb"), spaceAfter=2 * mm)
    subtitle_style = ParagraphStyle("InvSubtitle", parent=styles["Normal"], fontSize=8, textColor=colors.grey, spaceAfter=4 * mm)
    heading_style = ParagraphStyle("InvHeading", parent=styles["Heading3"], fontSize=10, textColor=colors.HexColor("#1e40af"), spaceAfter=2 * mm)
    normal = styles["Normal"]
    small = ParagraphStyle("Small", parent=normal, fontSize=8)

    elements = []

    elements.append(Paragraph("Tax Invoice", title_style))
    elements.append(Paragraph("Generated by DoAide E-Invoice | einvoice.doaide.com", subtitle_style))

    doc_dtls = data.get("DocDtls", {})
    elements.append(Paragraph(f"<b>Invoice No:</b> {doc_dtls.get('No', '')} &nbsp;&nbsp; <b>Date:</b> {doc_dtls.get('Dt', '')}", normal))
    elements.append(Spacer(1, 4 * mm))

    seller = data.get("SellerDtls", {})
    buyer = data.get("BuyerDtls", {})

    party_data = [
        ["Seller Details", "Buyer Details"],
        [
            Paragraph(f"<b>{seller.get('LglNm', '')}</b><br/>GSTIN: {seller.get('Gstin', '')}<br/>{seller.get('Addr1', '')}<br/>{seller.get('Loc', '')} - {seller.get('Pin', '')}", small),
            Paragraph(f"<b>{buyer.get('LglNm', '')}</b><br/>GSTIN: {buyer.get('Gstin', '')}<br/>{buyer.get('Addr1', '')}<br/>{buyer.get('Loc', '')} - {buyer.get('Pin', '')}", small),
        ],
    ]
    party_table = Table(party_data, colWidths=[doc.width / 2] * 2)
    party_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eff6ff")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#1e40af")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#dbeafe")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
    ]))
    elements.append(party_table)
    elements.append(Spacer(1, 4 * mm))

    elements.append(Paragraph("Item Details", heading_style))
    items = data.get("ItemList", [])
    item_header = ["#", "Description", "HSN", "Qty", "Rate", "Taxable", "IGST", "CGST", "SGST", "Total"]
    item_rows = [item_header]
    for it in items:
        item_rows.append([
            it.get("SlNo", ""),
            Paragraph(it.get("PrdDesc", ""), small),
            it.get("HsnCd", ""),
            str(it.get("Qty", "")),
            _num(it.get("UnitPrice", 0)),
            _num(it.get("AssAmt", 0)),
            _num(it.get("IgstAmt", 0)),
            _num(it.get("CgstAmt", 0)),
            _num(it.get("SgstAmt", 0)),
            _num(it.get("TotItemVal", 0)),
        ])

    col_widths = [8 * mm, 38 * mm, 18 * mm, 12 * mm, 18 * mm, 20 * mm, 16 * mm, 16 * mm, 16 * mm, 20 * mm]
    item_table = Table(item_rows, colWidths=col_widths, repeatRows=1)
    item_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2563eb")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 7),
        ("FONTSIZE", (0, 1), (-1, -1), 7),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#dbeafe")),
        ("ALIGN", (3, 0), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
    ]))
    elements.append(item_table)
    elements.append(Spacer(1, 4 * mm))

    vals = data.get("ValDtls", {})
    summary = [
        ["Taxable Value", _num(vals.get("AssVal", 0))],
        ["IGST", _num(vals.get("IgstVal", 0))],
        ["CGST", _num(vals.get("CgstVal", 0))],
        ["SGST", _num(vals.get("SgstVal", 0))],
        ["Total Invoice Value", _num(vals.get("TotInvVal", 0))],
    ]
    sum_table = Table(summary, colWidths=[doc.width - 40 * mm, 40 * mm])
    sum_table.setStyle(TableStyle([
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("LINEABOVE", (0, -1), (-1, -1), 1, colors.HexColor("#2563eb")),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    elements.append(sum_table)
    elements.append(Spacer(1, 8 * mm))
    elements.append(Paragraph("This is a computer-generated document. Generated by DoAide E-Invoice (einvoice.doaide.com)", ParagraphStyle("Disclaimer", parent=small, textColor=colors.grey, fontSize=7)))

    doc.build(elements)
    return buf.getvalue()
